import { buildLine, offerTotal } from "@/lib/pricing";
import { productById } from "@/lib/products";
import type { CrmData, DiscountId, PriceMode, Product } from "@/lib/types";

function product(id: string): Product {
  const found = productById(id);
  if (!found) throw new Error(id);
  return found;
}

function line(
  id: string,
  productId: string,
  quantity: number,
  discountId: DiscountId,
  priceMode: PriceMode,
) {
  return buildLine(product(productId), quantity, discountId, priceMode, id);
}

